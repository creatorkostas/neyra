        row.addWidget(self.run_command)
        self.speak = QPushButton("Speak command")
        self.speak.setObjectName("primary")
        self.speak.clicked.connect(self.speak_requested)
        row.addWidget(self.speak)
        command_box.addLayout(row)
        self.command_result = editor("Command results appear here.", True)
