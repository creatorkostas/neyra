    def page(self, title):
        page = QWidget()
        box = QVBoxLayout(page)
        box.setContentsMargins(16, 14, 16, 14)
        box.setSpacing(10)
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setWidget(page)
        self.tabs.addTab(scroll, title)
        return page

    def set_busy(self, busy):
        for widget in (self.login, self.logout, self.accounts, self.explain, self.ask, self.extract, self.run_command):
            widget.setEnabled(not busy)
        self.cancel.setVisible(busy)

    def set_capture_state(self, recording, busy):
        self.speak.setText("Finish command" if recording else "Speak command")
        self.speak.setEnabled(recording or not busy)
