        knowledge = self.page("Ask notes").layout()
        knowledge.addWidget(note("Find passages from your saved notes, review what you're sharing, then ask ChatGPT."))
        row = QHBoxLayout()
        self.question = QLineEdit()
        self.question.setPlaceholderText("What did we decide about the launch?")
        self.question.setMaxLength(2000)
        row.addWidget(self.question, 1)
        self.find_notes = QPushButton("Find notes")
        row.addWidget(self.find_notes)
