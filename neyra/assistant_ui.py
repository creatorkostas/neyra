"""Assistant workspace: explicit context, useful actions, and ChatGPT connection."""
from PySide6.QtCore import Qt, Signal, QDateTime, QSize
from PySide6.QtWidgets import (
    QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton, QTabWidget,
    QLineEdit, QTextEdit, QFrame, QListWidget, QDateTimeEdit, QScrollArea,
)
from .ui import DashboardComboBox


def note(text):
    label = QLabel(text)
    label.setObjectName("muted")
    label.setWordWrap(True)
    label.setTextFormat(Qt.TextFormat.PlainText)
    return label


class AssistantTextEdit(QTextEdit):
    def sizeHint(self):
        return QSize(280, 110)


def editor(placeholder, readonly=False):
    widget = AssistantTextEdit()
    widget.setMinimumHeight(78)
    widget.setAcceptRichText(False)
    widget.setPlaceholderText(placeholder)
    widget.setAccessibleName(placeholder)
    widget.setReadOnly(readonly)
    return widget


def date_input():
    widget = QDateTimeEdit(QDateTime.currentDateTime().addSecs(3600))
    widget.setCalendarPopup(True)
    widget.setDisplayFormat("ddd, dd MMM yyyy  HH:mm")
    widget.setAccessibleName("Date and time")
    return widget


