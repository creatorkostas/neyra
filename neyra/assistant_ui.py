from .ui import DashboardComboBox


def note(text):
    label = QLabel(text)
    label.setObjectName("muted")
    label.setWordWrap(True)
    label.setTextFormat(Qt.TextFormat.PlainText)
    return label


class AssistantTextEdit(QTextEdit):
    def sizeHint(self):
        return QSize(280, 110)


def editor(placeholder, readonly=False):
    widget = AssistantTextEdit()
    widget.setMinimumHeight(78)
    widget.setAcceptRichText(False)
    widget.setPlaceholderText(placeholder)
    widget.setAccessibleName(placeholder)
    widget.setReadOnly(readonly)
    return widget


class AssistantDateTimeEdit(QDateTimeEdit):
    def paintEvent(self, event):
        super().paintEvent(event)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        color = "#565a6a" if self.isEnabled() else "#979087"
        painter.setPen(QPen(QColor(color), 1.6, Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap))
        x, y = self.width() - 19, self.height() // 2
        painter.drawLine(x - 4, y - 2, x, y + 2)
        painter.drawLine(x, y + 2, x + 4, y - 2)


def date_input():
    widget = AssistantDateTimeEdit(QDateTime.currentDateTime().addSecs(3600))
    widget.setCalendarPopup(True)
    widget.setDisplayFormat("ddd, dd MMM yyyy  HH:mm")
    widget.setAccessibleName("Date and time")
    return widget


